export const TEXTOS_BASE = Object.fromEntries(
  TEXTOS_PORTAL.map(({ clave, campos }) => [clave, Object.fromEntries(campos.map(([campo, , base]) => [campo, base]))]),
);

const VARIABLE = /\{([^{}]+)\}/g;

/** Variables ({n}, {precio}...) que usa un texto de fábrica: son las que se pueden escribir en ese campo. */
export const variablesDe = (texto) => [...new Set(texto.match(VARIABLE) ?? [])];

/** Reemplaza las variables de un texto; las que no se conocen se dejan tal cual. */
export const formatear = (texto, variables) =>
  variables
    ? texto.replace(VARIABLE, (todo, nombre) => (nombre in variables ? String(variables[nombre] ?? '') : todo))
    : texto;

/** Convierte **texto** en negrita. */
export const conNegrita = (texto) =>
  texto.split('**').map((parte, i) => (i % 2 ? <strong key={i}>{parte}</strong> : parte));

/** Textos guardados sobre los de fábrica; uno vacío vuelve al de fábrica. */
export const combinarTextos = (guardados) =>
  Object.fromEntries(
    Object.entries(TEXTOS_BASE).map(([grupo, campos]) => [
      grupo,
      Object.fromEntries(
        Object.entries(campos).map(([campo, base]) => {
          const valor = guardados?.[grupo]?.[campo];
          return [campo, typeof valor === 'string' && valor.trim() ? valor.slice(0, MAX_TEXTO) : base];
        }),
      ),
    ]),
  );
